"""Conform original narration, generate original score/foley, and export film captions."""
import json
import math
import random
import re
import subprocess
import sys
import tempfile
import wave
from array import array
from pathlib import Path

root = Path(__file__).resolve().parents[1]
media = root / "media"
starts = [0, 8, 23, 34, 48, 65, 83, 99, 114, 130, 143, 158]
names = ["Cold Open", "The Moment I Failed Him", "After School", "The Strange Shop", "The Price", "The Do-Over", "The Missing Treehouse Memory", "Refunds Cost More", "The Photograph", "The Name He Forgot", "What Lucas Paid", "Meeting Again"]
finish, rate = 174, .94
sample_rate = 22050
lines = (media / "NARRATION_FIRST_PERSON.txt").read_text().strip().split("\n\n")
alignment = (media / "voice-alignment.txt").read_text().splitlines()
scenes = []
for scene in range(12):
    begin, end = map(float, alignment[scene*2].split()[:2])
    times = [float(value.split("=")[1]) for value in alignment[scene*2+1].split()]
    words = re.findall(r"[^\s]+", lines[scene])
    # PocketSphinx indexes the parts of the single hyphenated word separately.
    if "empty-handed." in words:
        times.pop(words.index("empty-handed.") + 1)
    assert len(words)==len(times), (scene,len(words),len(times))
    begin = max(0, begin - .045)
    end += .055
    captions = []
    i = 0
    while i < len(words):
        j = i+1
        while j < min(i+8,len(words)):
            if len(" ".join(words[i:j+1])) > 46 or j-i>=3 and re.search(r'[.!?]["”]?$',words[j-1]):
                break
            j += 1
        if len(words)-j==1 and len(" ".join(words[i:])) < 51:
            j += 1
        start = starts[scene]+(times[i]-begin)/rate
        stop = starts[scene]+((times[j] if j<len(words) else end)-begin)/rate
        captions.append([round(start,3), round(stop,3), " ".join(words[i:j])])
        i = j
    scenes.append({"id": scene+1,"name":names[scene],"start": starts[scene],"end": (starts+[finish])[scene+1],
                   "source_in": round(begin,3),"source_out": round(end,3),"narration":lines[scene],"captions":captions})
    assert starts[scene]+(end-begin)/rate <= (starts+[finish])[scene+1]

(media/"STORY_TIMELINE.json").write_text(json.dumps({"duration":finish,"voice_rate":rate,"scenes":scenes},ensure_ascii=False,indent=2)+"\n")
def stamp(t):
    s,ms=divmod(round(t*1000),1000)
    m,s=divmod(s,60)
    h,m=divmod(m,60)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"
all_cues=[cue for scene in scenes for cue in scene["captions"]]
(media/"SecondChances.srt").write_text("\n".join(f"{i}\n{stamp(a)} --> {stamp(b)}\n{line}\n" for i,(a,b,line) in enumerate(all_cues,1)))
lua = ["-- Generated by tools/build_audio.py", "return {",
       f"rate={rate}, finish={finish}, starts={{{','.join(map(str,starts))}}},", "captions={"]
for scene in scenes:
    lua.append("{")
    for a,b,line in scene["captions"]:
        lua.append(f"{{{a},{b},{json.dumps(line,ensure_ascii=False)}}},")
    lua.append("},")
(root/"src/NarrationTiming.luau").write_text("\n".join(lua+["},","}",""]))

sound = array("f",[0]) * (sample_rate*finish)
rng = random.Random(731)
def strike(time, duration, freq, volume, style):
    offset = round(time*sample_rate)
    for i in range(min(round(duration*sample_rate), len(sound)-offset)):
        t=i/sample_rate
        onset=min(1,t/.028)
        end=min(1,(duration-t)/.18)
        if style=="piano":
            phase=2*math.pi*freq*t
            sample=(math.sin(phase)+.34*math.sin(phase*2.002)+.11*math.sin(phase*3.01))*math.exp(-2.7*t)
        elif style=="tick":
            sample=(.7*math.sin(6.28*freq*t)+.3*rng.uniform(-1,1))*math.exp(-21*t)
        elif style=="bell":
            sample=(math.sin(6.28*freq*t)+.2*math.sin(6.28*freq*2.41*t))*math.exp(-4.2*t)
        else:
            sample=(rng.uniform(-1,1)*.31+math.sin(6.28*(freq*t+55*t*t))*.25)*min(1,t*3)*end
        sound[offset+i]+=sample*onset*end*volume
def note(midi): return 440*2**((midi-69)/12)

# Three sparse leitmotifs. The final arpeggio answers the unresolved first phrase.
themes = [(0,[45,52,57,60,64],.038),(24,[43,50,55,58,62],.026),
          (35,[45,52,57,60,64],.033),(49,[41,48,53,57,60],.034),
          (72,[48,55,60,64,67],.043),(83,[45,52,57,60,64],.026),
          (101,[41,48,53,57,60],.029),(115,[48,55,60,64,67],.038),
          (132,[43,50,55,58,62],.023),(145,[41,48,53,57,60],.038),
          (158,[48,55,60,64,67],.043),(166,[45,52,57,60,64],.036),
          (170,[48,55,60,64,72],.044)]
for t,chord,g in themes:
    for k,pitch in enumerate(chord):
        strike(t+(.38 if t>=158 else .57)*k,3.4,note(pitch),g,"piano")
    if t<156:
        strike(t+3.72,3.2,note(chord[-2]),g*.53,"piano")
for t in [.14,.58,1.01,1.61,43.2,43.87,44.52,48.92,51.2,104,136.7,148.1]:
    strike(t,.26,420,.079,"tick")
for t,f in [(23.12,520),(40.14,780),(40.27,1170),(100,760),(100.12,1140),(114.5,165),(114.64,155),(121.02,920),(121.31,1170)]:
    strike(t,.82,f,.055,"bell")
for t in [66.06,66.51,86.74,120.88,150.44]:
    strike(t,1.21,84,.075,"noise")
for t in [23.6,24.12,24.66,25.2,99.19,99.51,99.82,100.13,143.1,143.43,143.75,159,159.44,159.84]:
    strike(t,.19,76,.063,"tick")
# Quiet moving water under the final scene.
for t in range(158,174):
    strike(t,1.7,49+t%3,.024,"noise")

if len(sys.argv)>1:
    with tempfile.TemporaryDirectory() as tmp:
        foley=Path(tmp)/"score.wav"
        with wave.open(str(foley),"wb") as wav:
            wav.setparams((1,2,sample_rate,0,"NONE","not compressed"))
            wav.writeframes(array("h",(round(max(-1,min(1,x))*32767) for x in sound)).tobytes())
        cmd=["ffmpeg","-hide_banner","-loglevel","error","-y","-i",sys.argv[1],"-i",str(foley)]
        filters=[]
        for i,scene in enumerate(scenes):
            duration=(scene["source_out"]-scene["source_in"])/rate
            delay=round(scene["start"]*1000)
            filters.append(f"[0:a]atrim=start={scene['source_in']}:end={scene['source_out']},asetpts=PTS-STARTPTS,atempo={rate},afade=d=0.025,afade=t=out:st={duration-.035}:d=0.035,adelay={delay}:all=1[v{i}]")
        filters.append("".join(f"[v{i}]" for i in range(12))+"[1:a]amix=inputs=13:duration=longest:normalize=0,alimiter=limit=.94[mix]")
        subprocess.run(cmd+["-filter_complex",";".join(filters),"-map","[mix]","-ar","44100","-ac","1","-b:a","128k",str(media/"SecondChances-Mix.mp3")],check=True)
